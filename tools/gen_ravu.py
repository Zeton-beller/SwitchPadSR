#!/usr/bin/env python3
"""Converts the official bjin/mpv-prescalers ravu-lite-ar-r3.hook (LGPL-3.0)
into high-performance GLSL ES 3.00 shader and binary LUT texture for SwitchPadSR.

Generates:
  - app/src/main/assets/shaders/ravu_step1.frag (Single-pass subpixel reconstruction fragment shader)
  - app/src/main/assets/shaders/ravu_lut3.bin   (13x288 RGBA float32 binary texture, 59,904 bytes)
"""
import os, re, struct

hook_path = os.path.join(os.path.dirname(__file__), 'ravu-lite-ar-r3.hook')
if not os.path.exists(hook_path):
    raise FileNotFoundError(f"Missing {hook_path}")

out_dir = os.path.join(os.path.dirname(__file__), '..', 'app/src/main/assets/shaders')
os.makedirs(out_dir, exist_ok=True)

with open(hook_path, 'r', encoding='utf-8') as f:
    lines = f.readlines()

# 1. Extract hex binary data of ravu_lite_lut3 (Line 202, 0-indexed line 201)
hex_data = None
for i, line in enumerate(lines):
    if line.startswith('//!TEXTURE ravu_lite_lut3'):
        # Following lines are SIZE, FORMAT, FILTER, then hex data
        for j in range(i + 1, len(lines)):
            l = lines[j].strip()
            if l and not l.startswith('//!'):
                hex_data = l
                break
        break

if not hex_data:
    raise ValueError("Failed to find ravu_lite_lut3 hex data")

raw_bytes = bytes.fromhex(hex_data)
expected_bytes = 13 * 288 * 4 * 4 # 13 cols, 288 rows, 4 floats per texel, 4 bytes per float = 59,904 bytes
assert len(raw_bytes) == expected_bytes, f"Expected {expected_bytes} bytes, got {len(raw_bytes)}"

lut_bin_path = os.path.join(out_dir, 'ravu_lut3.bin')
with open(lut_bin_path, 'wb') as f:
    f.write(raw_bytes)
print(f"Generated {lut_bin_path} ({len(raw_bytes)} bytes)")

# 2. Extract and convert Hook 1 (step 1)
# Find start of hook 1
start_idx = None
end_idx = None
for i, line in enumerate(lines):
    if 'vec4 hook()' in line:
        start_idx = i
        break

for i in range(start_idx, len(lines)):
    if lines[i].startswith('//!DESC RAVU-Lite-AR (step2'):
        end_idx = i
        break

hook1_lines = lines[start_idx:end_idx]
body = "".join(hook1_lines)

# Transform taps:
# HOOKED_texOff(vec2(dx, dy)).x -> TX(dx, dy)
# Notice: bottom-up FBO storage means dy -> -dy in texelFetch clamp
def replace_tap(m):
    dx = m.group(1)
    dy = m.group(2)
    return f"TX({dx}, {dy})"

body = re.sub(r"HOOKED_texOff\(vec2\(([-0-9.]+),\s*([-0-9.]+)\)\)\.x", replace_tap, body)

# Replace ravu_lite_lut3 -> u_lut
body = body.replace("ravu_lite_lut3", "u_lut")

shader_code = """#version 300 es
precision highp float;
precision highp int;
precision highp sampler2D;
// AUTO-GENERATED by tools/gen_ravu.py from bjin/mpv-prescalers ravu-lite-ar-r3.hook (LGPL-3.0). Do not edit.
// RAVU-Lite-AR Step 1: Directional gradient tensor reconstruction with anti-ringing clamp.
// Reconstructs 4 subpixel luma values per source texel into RGBA16F tensor.

uniform sampler2D u_tex;  // LUMA source texture
uniform sampler2D u_lut;  // 13x288 RGBA float LUT texture (ravu_lite_lut3)
uniform ivec2 u_size;     // LUMA texture dimensions (w, h)
out vec4 o_color;

// Bottom-up texture coordinate mapping: mpv +dy maps to OpenGL -(dy)
#define TX(dx, dy) texelFetch(u_tex, clamp(ivec2(gl_FragCoord.xy) + ivec2(int(dx), -int(dy)), ivec2(0), u_size - 1), 0).r

""" + body + """

void main() {
    o_color = hook();
}
"""

frag_path = os.path.join(out_dir, 'ravu_step1.frag')
with open(frag_path, 'w', encoding='utf-8') as f:
    f.write(shader_code)
print(f"Generated {frag_path}")
