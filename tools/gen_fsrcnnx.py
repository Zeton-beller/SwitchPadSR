#!/usr/bin/env python3
"""Mechanically converts the official igv/FSRCNN-TensorFlow FSRCNNX_x2_8-0-4-1.glsl (mpv user-shader, LGPL-3.0)
into GLSL ES 3.00 fragment shaders (one per network layer) + a manifest.

Orientation: our FBOs are stored bottom-up (row 0 = image bottom), mpv's are top-down, so every (dx,dy)
tap becomes (dx,-dy) in texel space. The final aggregation is done in fsrcnnx_up.frag (same flip applied)."""
import re, sys, os
src = open(os.path.join(os.path.dirname(__file__), 'FSRCNNX_x2_8-0-4-1.glsl')).read()
out = os.path.join(os.path.dirname(__file__), '..', 'app/src/main/assets/shaders')
hooks = src.split('//!HOOK')[1:]
HEAD = """#version 300 es
precision highp float;
precision highp int;
precision highp sampler2D;
// AUTO-GENERATED by tools/gen_fsrcnnx.py from igv/FSRCNN-TensorFlow FSRCNNX_x2_8-0-4-1.glsl (LGPL-3.0). Do not edit.
%s
uniform ivec2 u_size;
out vec4 o_color;
#define TX(S, dx, dy) texelFetch(S, clamp(ivec2(gl_FragCoord.xy) + ivec2(dx, dy), ivec2(0), u_size - 1), 0)
"""
manifest = []
n = 0
for h in hooks:
    save = re.search(r'//!SAVE (\w+)', h)
    if not save:       # aggregation pass -> fsrcnnx_up.frag
        continue
    n += 1
    binds = re.findall(r'//!BIND (\w+)', h)
    body = h[h.index('vec4 hook()'):]
    def flip(m):
        return 'TX(%s, %s, %d)' % (m.group(1), m.group(2), -int(m.group(3)))
    body = re.sub(r'float\((\w+)_texOff\(vec2\((-?\d+),(-?\d+)\)\)\)',
                  lambda m: flip(m) + '.x', body)
    body = re.sub(r'(\w+)_texOff\(vec2\((-?\d+),(-?\d+)\)\)', flip, body)
    body = re.sub(r'(\w+)_texOff\(0\)', lambda m: 'TX(%s, 0, 0)' % m.group(1), body)
    assert '_texOff' not in body, body[:200]
    name = 'fsrcnnx_p%02d.frag' % n
    unis = ''.join('uniform sampler2D %s;\n' % b for b in binds)
    open(os.path.join(out, name), 'w').write(HEAD % unis + body + '\nvoid main() { o_color = hook(); }\n')
    manifest.append('%s %s %s' % (name, save.group(1), ','.join(binds)))
open(os.path.join(out, 'fsrcnnx_manifest.txt'), 'w').write('\n'.join(manifest) + '\n')
print('\n'.join(manifest))
